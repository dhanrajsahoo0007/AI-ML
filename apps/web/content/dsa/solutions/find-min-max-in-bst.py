from typing import List, Optional, Tuple


class TreeNode:
    def __init__(self, val: int = 0, left: Optional["TreeNode"] = None, right: Optional["TreeNode"] = None):
        self.val = val
        self.left = left
        self.right = right


def find_min_max(root: Optional[TreeNode]) -> Tuple[Optional[int], Optional[int]]:
    if root is None:
        return None, None
    lo = root
    while lo.left:
        lo = lo.left
    hi = root
    while hi.right:
        hi = hi.right
    return lo.val, hi.val


