// A 64-bit post id that sorts by time and carries its shard (instagram, Step 3 and Deep dive 1).
// Steps: 1 41 bits of milliseconds since a custom epoch, read from the database server's clock · 2 13 bits of
// logical shard: the author's shard, user id mod 8,192 · 3 10 bits of sequence: the shard's own counter, mod 1,024 ·
// 4 one post id taken apart, and how the shard bits route a read with no lookup.
// Working (computed below):
//   2^41 ms = 2,199,023,255,552 ms ÷ 31,557,600,000 ms a year (365.25 days) = 69.7 years. The id has no spare sign
//   bit (41 + 13 + 10 = 64), so in a signed 64-bit integer it stays positive only for 2^40 ms = 34.8 years.
//   2^13 = 8,192 logical shards. 2^10 = 1,024 ids per millisecond per shard = 1,024,000 a second per shard.
//   Example (illustrative): epoch 1 January 2026 00:00 UTC; a post on 17 November 2026 09:30:00.000 UTC is
//   320 days 9.5 hours = 27,682,200,000 ms later. Author 31,341: 31,341 mod 8,192 = 6,765. The shard's sequence is
//   at 5,001: 5,001 mod 1,024 = 905. (27,682,200,000 << 23) | (6,765 << 10) | 905 = 232,215,124,384,528,265.
//   Routing: (id >> 10) & 8,191 = 6,765; 8,192 logical shards on 64 databases is 128 each, so 6,765 ÷ 128 → DB 52.
// Layout: the 64 bits as one bar, 11 px a bit; sources above, capacities below, the example under them.
// Colours (PATTERN_TONE): time pink (a clock counter), shard violet (the store), sequence green (the counter that
// makes ids unique within a millisecond, highlighted), the example blue (data), bit numbers neutral.
// Fact check (2026-11-17, "Sharding & IDs at Instagram", Instagram Engineering, 30 December 2012, read via the
// Internet Archive): 41 bits of milliseconds with a custom epoch, 13 bits of logical shard id, 10 bits of an
// auto-increment sequence mod 1,024, generated by a PL/pgSQL function in each shard's schema. The epoch, author and
// sequence here are our own illustrative values.

const BIT = 11;
const X0 = 60;
const BAR_Y = 124;
const BAR_H = 44;
const TIME_BITS = 41;
const SHARD_BITS = 13;
const SEQ_BITS = 10;
const LOGICAL = 2 ** SHARD_BITS; // 8,192
const PHYSICAL = 64;
const PER_DB = LOGICAL / PHYSICAL; // 128

const YEAR_MS = 365.25 * 86_400_000;
const years = 2 ** TIME_BITS / YEAR_MS; // 69.7
const signedYears = 2 ** (TIME_BITS - 1) / YEAR_MS; // 34.8
const perMs = 2 ** SEQ_BITS; // 1,024

const epoch = Date.UTC(2026, 0, 1);
const postAt = Date.UTC(2026, 10, 17, 9, 30, 0, 0);
const t = postAt - epoch; // 27,682,200,000 ms
const AUTHOR = 31_341;
const SHARD = AUTHOR % LOGICAL; // 6,765
const SEQ_RAW = 5_001;
const SEQ = SEQ_RAW % perMs; // 905
const id = (BigInt(t) << BigInt(SHARD_BITS + SEQ_BITS)) | (BigInt(SHARD) << BigInt(SEQ_BITS)) | BigInt(SEQ);
const idText = id.toLocaleString("en-GB"); // 232,215,124,384,528,265
const db = Math.floor(SHARD / PER_DB); // 52

const timeX = X0;
const timeW = TIME_BITS * BIT;
const shardX = timeX + timeW;
const shardW = SHARD_BITS * BIT;
const seqX = shardX + shardW;
const seqW = SEQ_BITS * BIT;
const barEnd = seqX + seqW;

const shapes: LayoutShape[] = [];

