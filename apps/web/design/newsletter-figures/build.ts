import fs from "node:fs";
import path from "node:path";
import yaml from "js-yaml";

// Writes every issue's figures as SVG assets with sidecars:
//   npm run figures:newsletter -w web            all issues
//   npm run figures:newsletter -w web -- <issue> one issue
// Output: assets/diagrams/svg/newsletter/<issue>/<figure>.svg (+ .meta.yaml). Commit both; the asset pipeline
// takes it from there. Edit the figure code here, never the generated SVG.

export interface FigureDef {
  slug: string;
  svg: () => string;
  meta: {
    title: string;
    /** What the figure shows, for screen readers. */
    alt: string;
    /** The one thing to notice (shown under the figure). */
    caption: string;
    /** One line for the LinkedIn carousel slide (defaults to the caption). */
    slide?: string;
  };
}

const ISSUES: Record<string, () => Promise<{ figures: FigureDef[] }>> = {
  "harness-engineering": () => import("./harness-engineering"),
  "loop-engineering": () => import("./loop-engineering"),
};

const OUT = path.join(process.cwd(), "assets", "diagrams", "svg", "newsletter");

async function main() {
  const only = process.argv[2];
  const keys = only ? [only] : Object.keys(ISSUES);
  for (const key of keys) {
    const load = ISSUES[key];
    if (!load) throw new Error(`unknown issue "${key}"; known: ${Object.keys(ISSUES).join(", ")}`);
    const dir = path.join(OUT, key);
    fs.mkdirSync(dir, { recursive: true });
    for (const f of (await load()).figures) {
      fs.writeFileSync(path.join(dir, `${f.slug}.svg`), f.svg());
      const sidecar =
        `# Generated by design/newsletter-figures/build.ts (${key}.ts); edit the figure code, not this file.\n` +
        yaml.dump({ ...f.meta, tags: ["newsletter", key], source: "original" }, { lineWidth: 120, quotingType: '"' });
      fs.writeFileSync(path.join(dir, `${f.slug}.meta.yaml`), sidecar);
      console.log(`figures: wrote ${path.relative(process.cwd(), path.join(dir, f.slug))}.svg`);
    }
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
