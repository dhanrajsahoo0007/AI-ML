// Constants for the Agent2Agent (A2A) figures (assets/diagrams/animated/agents/a2a-discovery, a2a-task-lifecycle,
// a2a-vs-mcp) on genai-system-design/agent-to-agent-protocols. Brightpost names come from ./agents and its MCP
// servers from ./agents-tools; this file adds the courier company whose agent Brightpost's support agent delegates to.
//
// The story: the kettle for order 4471 arrived cracked, so after the refund Brightpost's support agent files a damage
// claim with the courier's claims agent over A2A. The courier's agent asks for a photo (the task goes to
// TASK_STATE_INPUT_REQUIRED), Brightpost sends one on the same task, and the claim comes back as an artifact. The
// courier, its domain, the tracking number, the claim id and the collection date are invented for the example
// (domains use the reserved .example TLD, RFC 2606).
//
// Protocol facts follow the A2A specification v1.0 (release v1.0.1, 28 May 2026; a2aproject/A2A docs/specification.md
// and specification/a2a.proto, checked 2026-11-15): the card at /.well-known/agent-card.json, the field names, the
// TaskState values and the Part content fields.

