export function getIconComponent(name: string): LucideIcon | undefined {
  return iconMap[name];
}

export function resolveIcon(icon: string): React.ReactNode {
  const Icon = iconMap[icon];
  if (Icon) {
    return React.createElement(Icon, { className: "h-6 w-6" });
  }
  return React.createElement("span", { className: "text-2xl" }, icon);
}

export function resolveCategoryIcon(icon: string): React.ReactNode {
  const Icon = iconMap[icon];
  if (Icon) {
    return React.createElement(Icon, { className: "h-7 w-7" });
  }
  return React.createElement("span", { className: "text-3xl" }, icon);
}
